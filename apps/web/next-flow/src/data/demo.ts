function demoOrder(id: string, tableId: string, sessionId: string, status: Order["status"], minutes: number, itemId: string): Order {
  const item = menuItems.find((menu) => menu.id === itemId) ?? menuItems[0];
  const createdAt = minutesAgo(minutes);
  return {
    id,
    tableId,
    sessionId,
    status,
    createdAt,
    acceptedAt: status !== "PENDING_CONFIRMATION" ? minutesAgo(Math.max(minutes - 1, 0)) : undefined,
    preparingAt: ["PREPARING", "READY", "SERVED"].includes(status) ? minutesAgo(Math.max(minutes - 2, 0)) : undefined,
    readyAt: ["READY", "SERVED"].includes(status) ? minutesAgo(Math.max(minutes - 6, 0)) : undefined,
    servedAt: status === "SERVED" ? minutesAgo(Math.max(minutes - 8, 0)) : undefined,
    items: [
      {
        id: `${id}-item-1`,
        menuItemId: item.id,
        name: item.name,
        quantity: 1,
        basePrice: item.price,
        modifiers: [],
      },
    ],
  };
}

